import sys

# Встановлюємо кодування для коректного виведення кирилиці в консолі (для Windows)
if sys.platform.startswith('win'):
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

# --- 1. Введення даних ---
try:
    rows_num = int(input("Введіть розмір квадратної матриці: "))
except ValueError:
    print("Помилка: Введено не ціле число.")
    sys.exit(1)

filler = input("Введіть символ-заповнювач: ")

# --- 2. Перевірка коректності символу ---
# Якщо рядок порожній або має більше 1 символу - вихід
if len(filler) == 0:
    print("Помилка: Не введено символ-заповнювач.")
    sys.exit(1)
elif len(filler) > 1:
    print("Помилка: Забагато символів-заповнювачів.")
    sys.exit(1)

# --- 3. Формування зубчатого списку (Upper Triangle) ---
# Для верхнього трикутника кількість елементів у рядку зменшується:
# Рядок 0: N елементів
# Рядок 1: N-1 елементів
# ...
lst = []

for i in range(rows_num):
    row = []
    # Заповнюємо рядок. Кількість елементів = rows_num - i
    for j in range(rows_num - i):
        # Зберігаємо код символу (згідно з прикладом у методичці) 
        # або сам символ. Тут зручніше зберігати сам символ.
        row.append(filler)
    lst.append(row)

# --- 4. Виведення результату на екран ---
print("\nРезультат:")

for i in range(len(lst)):
    # Виводимо відступи для формування форми трикутника
    # Кожен наступний рядок зміщується вправо на 2 пробіли
    print("  " * i, end="")
    
    for j in range(len(lst[i])):
        # Виводимо елемент списку
        print(lst[i][j], end=" ")
    
    # Перехід на новий рядок
    print()

# Підтвердження завершення
print(f"\nРоботу завершено. Розмір масиву: {len(lst)}")